/** The path of a row's icon, by its label. */
export function rmRowIconPath(label) {
  const found = RM_ROW_ICONS.find(([pattern]) => pattern.test(label));
  return RM_ICON_PATHS[found ? found[1] : 'insights'];
}

/** The same icon as inline SVG, for the pop-up's static HTML; `color`, when given, is its status colour. */
export function rmIconSvg(path, color) {
  return `<svg viewBox="0 0 24 24" aria-hidden="true"${color ? ` style="fill:${color}"` : ''}><path d="${path}"/></svg>`;
}
